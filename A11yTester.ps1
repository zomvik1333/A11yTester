        '<a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic><pic:nvPicPr><pic:cNvPr id="' + $n + '" name="image' + $n + '"/><pic:cNvPicPr/></pic:nvPicPr>' +

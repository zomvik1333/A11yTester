    try { $ok = Invoke-Js $Conn '!!(window.__a11y && window.__a11y.v === 3 && window.__a11y.srChecks && window.__a11y.zoomCheck)' } catch { }
    if (-not $ok) { Invoke-Js $Conn $Script:JsBundle | Out-Null }

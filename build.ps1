# Builds A11yTester.ps1, the single file people copy to their work computer.
# Run from the repo folder:  powershell -ExecutionPolicy Bypass -File .\build.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$version = (Get-Content -LiteralPath (Join-Path $root 'VERSION') -Raw).Trim()

function Read-Src([string]$rel) { return (Get-Content -LiteralPath (Join-Path $root $rel) -Raw -Encoding UTF8).TrimEnd() }

$ps = @('src/driver/Cdp.ps1', 'src/driver/Browser.ps1', 'src/driver/TestScreen.ps1', 'src/driver/Main.ps1',
        'src/report/Rules.ps1', 'src/report/Docx.ps1', 'src/report/Report.ps1')
$js = @('src/browser/common.js', 'src/browser/zoom.js', 'src/browser/keyboard.js', 'src/browser/screenreader.js')

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine(@"
<#
  A11y Tester $version
  Local WCAG 2.2 accessibility tester for web apps. Tests zoom, keyboard use and
  screen reader output, then writes a plain English Word report.

  Nothing is downloaded and nothing leaves this computer. It uses only Windows
  PowerShell, Microsoft Edge (or Chrome) and files it writes to your Documents folder.

  How to run, from a VS Code terminal in this folder:
      powershell -ExecutionPolicy Bypass -File .\A11yTester.ps1

  This file is generated by build.ps1 from the src folder. Edit the src files, not this one.
  Source and instructions: https://github.com/vanarissolutions-ops/A11yTester
#>
[CmdletBinding()]
param(
    [string]`$AppName, [string]`$Url, [ValidateSet('', 'Guided', 'Links')][string]`$Mode = '', [string[]]`$Links,
    [string]`$DataDir, [string]`$ResultsDir, [string]`$BrowserPath, [switch]`$Headless, [switch]`$NoSandbox, [switch]`$NoOpen,
    [string[]]`$Skip = @(), [switch]`$KeepLogin
)
`$Script:ToolVersion = '$version'
"@)

foreach ($f in $ps) {
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('#region ' + $f)
    [void]$sb.AppendLine((Read-Src $f))
    [void]$sb.AppendLine('#endregion')
}

$toolbar = Read-Src 'src/browser/toolbar.js'
$bundle = ($js | ForEach-Object { Read-Src $_ }) -join "`n"
foreach ($chunk in @($toolbar, $bundle)) { if ($chunk -match "(?m)^'@") { throw 'JavaScript contains a line starting with an apostrophe and @ which would break the here-string.' } }

[void]$sb.AppendLine('')
[void]$sb.AppendLine('#region Browser scripts (src/browser)')
[void]$sb.AppendLine("`$Script:JsToolbar = @'")
[void]$sb.AppendLine($toolbar)
[void]$sb.AppendLine("'@")
[void]$sb.AppendLine("`$Script:JsBundle = @'")
[void]$sb.AppendLine($bundle)
[void]$sb.AppendLine("'@")
[void]$sb.AppendLine('#endregion')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('$null = Invoke-A11yMain @PSBoundParameters')

$text = $sb.ToString() -replace "`r`n", "`n"
$bad = [regex]::Matches($text, '[^\x09\x0A\x0D\x20-\x7E]')
if ($bad.Count -gt 0) {
    $first = $bad[0]
    $line = ($text.Substring(0, $first.Index) -split "`n").Count
    throw ("Non ASCII character U+{0:X4} on line {1}. Keep the file plain ASCII so it survives copy and paste." -f [int][char]$first.Value, $line)
}
$out = Join-Path $root 'A11yTester.ps1'
[System.IO.File]::WriteAllText($out, ($text -replace "`n", "`r`n"), (New-Object System.Text.UTF8Encoding($false)))
$kb = [Math]::Round((Get-Item -LiteralPath $out).Length / 1KB)
Write-Host "Built A11yTester.ps1 version $version ($kb KB)"

function Write-Log {
    param([string]$Text)
    $line = (Get-Date).ToString('HH:mm:ss') + '  ' + $Text
    if ($Script:LogPath) { Add-Content -LiteralPath $Script:LogPath -Value $line -Encoding UTF8 }
}

function Write-Step {
    param([string]$Text, [string]$Color = 'Gray')
    Write-Host ('  ' + $Text) -ForegroundColor $Color
    Write-Log $Text
}

